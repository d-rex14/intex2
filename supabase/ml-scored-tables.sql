-- ---------------------------------------------------------------------------
-- 3. resident_ml_scores
--    Populated by: ml-pipelines/reintegration-readiness.ipynb,
--                  ml-pipelines/school-struggle-risk.ipynb,
--                  ml-pipelines/resident-wellbeing-prediction.ipynb,
--                  ml-pipelines/02_incident_leading_indicators/
--    Read by: /portal/caseload (CaseloadPage)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.resident_ml_scores (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resident_id             integer NOT NULL,          -- FK to residents table
  reintegration_band      text                       -- 'Ready' | 'Approaching' | 'Not Ready' | null
    CHECK (reintegration_band IN ('Ready', 'Approaching', 'Not Ready') OR reintegration_band IS NULL),
  reintegration_score     numeric(6, 4),
  school_struggle_band    text
    CHECK (school_struggle_band IN ('High', 'Medium', 'Low') OR school_struggle_band IS NULL),
  school_struggle_score   numeric(6, 4),
  wellbeing_band          text
    CHECK (wellbeing_band IN ('High', 'Medium', 'Low') OR wellbeing_band IS NULL),
  wellbeing_score         numeric(6, 4),
  incident_risk_band      text
    CHECK (incident_risk_band IN ('High', 'Medium', 'Low') OR incident_risk_band IS NULL),
  incident_risk_score     numeric(6, 4),
  model_version           text NOT NULL DEFAULT '1.0',
  scored_at               timestamptz NOT NULL DEFAULT now(),
  UNIQUE (resident_id)
);

ALTER TABLE public.resident_ml_scores ENABLE ROW LEVEL SECURITY;

