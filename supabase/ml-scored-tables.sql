-- Watchtower ML Scored Tables
-- Run in the Supabase SQL Editor AFTER creating these tables.
-- Scores are batch-written by the ml-pipelines notebooks and read
-- by the portal UI via useSupabaseQuery.

-- ---------------------------------------------------------------------------
-- 1. donor_upgrade_scores
--    Populated by: ml-pipelines/04_donor_upgrade_predictor/
--    Read by: /portal/donors (DonorsContributionsPage)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.donor_upgrade_scores (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supporter_id        integer NOT NULL REFERENCES public.supporters(supporter_id) ON DELETE CASCADE,
  score               numeric(6, 4) NOT NULL,        -- predict_proba value 0.0–1.0
  band                text NOT NULL                  -- 'High' | 'Medium' | 'Low'
    CHECK (band IN ('High', 'Medium', 'Low')),
  recommended_action  text,                          -- plain-language staff suggestion
  model_version       text NOT NULL DEFAULT '1.0',
  scored_at           timestamptz NOT NULL DEFAULT now(),
  UNIQUE (supporter_id)                              -- one active score per supporter
);

-- RLS: staff/admin can read; only service-role (notebook export) can write.
ALTER TABLE public.donor_upgrade_scores ENABLE ROW LEVEL SECURITY;

CREATE POLICY "staff_read_donor_upgrade_scores"
  ON public.donor_upgrade_scores
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.user_roles ur
      WHERE ur.user_id = auth.uid()
        AND ur.role_id IN (3, 4)  -- staff=3, admin=4
    )
  );

