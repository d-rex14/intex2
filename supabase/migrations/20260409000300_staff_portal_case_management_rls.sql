-- Optional: allow authenticated users to read safehouse names/capacity for dashboard UI.
-- (Portal dashboard queries safehouses; if you already have broader policies, this is redundant.)
DROP POLICY IF EXISTS safehouses_staff_select ON public.safehouses;
CREATE POLICY safehouses_staff_select
  ON public.safehouses
  FOR SELECT
  TO authenticated
  USING (public.is_staff_portal_user());

-- If safehouses had no RLS before, enable it so the SELECT policy takes effect.
ALTER TABLE public.safehouses ENABLE ROW LEVEL SECURITY;

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. Keep safehouses.current_occupancy in sync with Active residents per house
-- ─────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.trg_residents_refresh_safehouse_occupancy()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.safehouse_id IS NOT NULL THEN
      UPDATE public.safehouses s
      SET current_occupancy = (
        SELECT COUNT(*)::int
        FROM public.residents r
        WHERE r.safehouse_id = OLD.safehouse_id
          AND r.case_status = 'Active'
      )
      WHERE s.safehouse_id = OLD.safehouse_id;
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF OLD.safehouse_id IS NOT NULL
       AND (
         OLD.safehouse_id IS DISTINCT FROM NEW.safehouse_id
         OR OLD.case_status IS DISTINCT FROM NEW.case_status
       )
    THEN
      UPDATE public.safehouses s
      SET current_occupancy = (
        SELECT COUNT(*)::int
        FROM public.residents r
        WHERE r.safehouse_id = OLD.safehouse_id
          AND r.case_status = 'Active'
      )
      WHERE s.safehouse_id = OLD.safehouse_id;
    END IF;
    IF NEW.safehouse_id IS NOT NULL
       AND (
         OLD.safehouse_id IS DISTINCT FROM NEW.safehouse_id
         OR OLD.case_status IS DISTINCT FROM NEW.case_status
       )
    THEN
      UPDATE public.safehouses s
      SET current_occupancy = (
        SELECT COUNT(*)::int
        FROM public.residents r
        WHERE r.safehouse_id = NEW.safehouse_id
          AND r.case_status = 'Active'
      )
      WHERE s.safehouse_id = NEW.safehouse_id;
    END IF;
    RETURN NEW;
  END IF;

  -- INSERT
  IF NEW.safehouse_id IS NOT NULL AND NEW.case_status = 'Active' THEN
    UPDATE public.safehouses s
    SET current_occupancy = (
      SELECT COUNT(*)::int
      FROM public.residents r
      WHERE r.safehouse_id = NEW.safehouse_id
        AND r.case_status = 'Active'
    )
    WHERE s.safehouse_id = NEW.safehouse_id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS residents_refresh_safehouse_occupancy ON public.residents;
CREATE TRIGGER residents_refresh_safehouse_occupancy
  AFTER INSERT OR UPDATE OR DELETE ON public.residents
  FOR EACH ROW
  EXECUTE FUNCTION public.trg_residents_refresh_safehouse_occupancy();

-- One-time reconciliation (optional but helpful after first deploy)
UPDATE public.safehouses sh
SET current_occupancy = (
  SELECT COUNT(*)::int
  FROM public.residents r
  WHERE r.safehouse_id = sh.safehouse_id
    AND r.case_status = 'Active'
);
